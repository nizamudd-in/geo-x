#!/usr/bin/env python3
"""
GeoSense-X — FAISS Index Builder
==================================
Loads pre-computed L2-normalised embeddings, builds an exact
inner-product (cosine) FAISS index, and saves it to disk.

Index choice — ``IndexFlatIP``
──────────────────────────────
  ``IndexFlatIP`` performs brute-force dot-product search.
  Because every embedding is L2-normalised to the unit hypersphere,
  inner-product == cosine similarity.  No training step is required.

  Trade-off table:
    Index type       Training  Recall  Speed (1M vecs)  Notes
    ─────────────────────────────────────────────────────────────
    IndexFlatIP      none       100%    ~50 ms           chosen — exact
    IndexIVFFlat     yes        ~97%    ~5 ms            approximate
    IndexIVFPQ       yes        ~90%    ~2 ms            compressed

  For Phase-1 (≤50K embeddings), brute-force is fast enough
  (<50 ms per query on CPU).  Swap to IndexIVFFlat in Phase-2
  when the catalog exceeds 100K scenes.

Normalisation note
──────────────────
  The embeddings produced by ``generate_embeddings.py`` are already
  L2-normalised (‖e‖₂ = 1.0 ± 1e-6).  ``faiss.normalize_L2()`` is
  called again here as a defensive guard — it is idempotent for
  unit vectors (no-op numerically).

Input
─────
  data/embeddings/train_embeddings.npy    [N, 512] float32
  data/embeddings/train_patch_keys.csv   [N rows]  patch_key, region_id

Output
──────
  data/index/faiss.index                  FAISS binary index
  data/index/index_meta.json              {n, d, index_type, source_file}

Usage
─────
  # Build from default train embeddings
  python backend/ml/faiss_index.py

  # Custom source file and output
  python backend/ml/faiss_index.py \\
      --embeddings data/embeddings/train_embeddings.npy \\
      --output     data/index/faiss.index

  # All splits merged into one index
  python backend/ml/faiss_index.py --merge-splits
"""
from __future__ import annotations

import argparse
import json
import logging
import sys
import time
from pathlib import Path

import faiss
import numpy as np

# ─────────────────────────────────────────────────────────────────────────────
# Project root
# ─────────────────────────────────────────────────────────────────────────────

_SCRIPT_DIR  = Path(__file__).resolve().parent      # backend/ml/
_BACKEND_DIR = _SCRIPT_DIR.parent                   # backend/
_PROJECT_DIR = _BACKEND_DIR.parent                  # ps11/

# ─────────────────────────────────────────────────────────────────────────────
# Logging
# ─────────────────────────────────────────────────────────────────────────────

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s  %(levelname)-8s  %(message)s",
    stream=sys.stdout,
)
logger = logging.getLogger(__name__)


# ─────────────────────────────────────────────────────────────────────────────
# Core builder
# ─────────────────────────────────────────────────────────────────────────────

def build_index(
    embeddings_path: Path,
    output_path:     Path,
    force_rebuild:   bool = False,
) -> faiss.Index:
    """
    Load embeddings, L2-normalise (defensive), build IndexFlatIP, save.

    Parameters
    ----------
    embeddings_path:
        Path to a ``.npy`` file containing an [N, D] float32 array.
        Embeddings must be L2-normalised (generated by generate_embeddings.py).
    output_path:
        Destination path for the serialised FAISS index binary.
        Parent directory is created if it does not exist.
    force_rebuild:
        If ``False`` (default) and ``output_path`` already exists, the
        existing index is loaded and returned without rebuilding.
        If ``True``, always rebuild.

    Returns
    -------
    faiss.Index
        The built (and saved) FAISS index.

    Raises
    ------
    FileNotFoundError:  ``embeddings_path`` does not exist.
    ValueError:         Embeddings array has wrong ndim or dtype.
    RuntimeError:       FAISS index reports zero vectors after add().
    """
    # ── Guard: skip rebuild if index already exists ────────────────────────
    if output_path.exists() and not force_rebuild:
        logger.info(
            "Index already exists at %s — loading (use --force to rebuild).",
            output_path,
        )
        index = faiss.read_index(str(output_path))
        logger.info(
            "Loaded existing index  |  ntotal=%d  d=%d",
            index.ntotal, index.d,
        )
        return index

    # ── 1. Load embeddings ─────────────────────────────────────────────────
    if not embeddings_path.exists():
        raise FileNotFoundError(
            f"Embeddings not found: {embeddings_path}\n"
            "Run: python backend/ml/generate_embeddings.py"
        )

    logger.info("Loading embeddings from %s ...", embeddings_path)
    embeddings = np.load(str(embeddings_path))

    if embeddings.ndim != 2:
        raise ValueError(
            f"Expected 2-D array [N, D], got shape {embeddings.shape}"
        )
    if embeddings.dtype != np.float32:
        logger.info(
            "Casting embeddings from %s to float32", embeddings.dtype
        )
        embeddings = embeddings.astype(np.float32)

    n, d = embeddings.shape
    logger.info(
        "Embeddings loaded  |  N=%d  D=%d  dtype=%s  size=%.2f MB",
        n, d, embeddings.dtype,
        embeddings.nbytes / 1_048_576,
    )

    # ── 2. L2-normalise (idempotent for unit vectors) ──────────────────────
    norms_before = np.linalg.norm(embeddings, axis=1)
    logger.info(
        "L2 norms before normalise  |  min=%.6f  max=%.6f",
        norms_before.min(), norms_before.max(),
    )

    faiss.normalize_L2(embeddings)          # in-place, contiguous C-array

    norms_after = np.linalg.norm(embeddings, axis=1)
    logger.info(
        "L2 norms after  normalise  |  min=%.6f  max=%.6f",
        norms_after.min(), norms_after.max(),
    )

    # ── 3. Build IndexFlatIP ───────────────────────────────────────────────
    logger.info("Building IndexFlatIP (d=%d) ...", d)
    t0    = time.perf_counter()
    index = faiss.IndexFlatIP(d)
    index.add(embeddings)
    elapsed = time.perf_counter() - t0

    if index.ntotal != n:
        raise RuntimeError(
            f"Index contains {index.ntotal} vectors but expected {n}. "
            "The add() call may have silently failed."
        )

    logger.info(
        "Index built  |  ntotal=%d  d=%d  index_type=%s  build_time=%.3fs",
        index.ntotal, index.d,
        index.__class__.__name__,
        elapsed,
    )

    # ── 4. Save index ──────────────────────────────────────────────────────
    output_path.parent.mkdir(parents=True, exist_ok=True)
    faiss.write_index(index, str(output_path))
    index_size_kb = output_path.stat().st_size / 1024
    logger.info(
        "Saved index  |  %s  (%.1f KB)",
        output_path, index_size_kb,
    )

    # ── 5. Save companion metadata ─────────────────────────────────────────
    meta_path = output_path.parent / "index_meta.json"
    meta = {
        "n":           n,
        "d":           d,
        "index_type":  index.__class__.__name__,
        "source_file": str(embeddings_path),
        "index_file":  str(output_path),
        "faiss_version": faiss.__version__,
    }
    with open(meta_path, "w", encoding="utf-8") as f:
        json.dump(meta, f, indent=2)
    logger.info("Saved metadata  |  %s", meta_path)

    return index


def merge_and_build(
    splits:      list[str],
    emb_dir:     Path,
    output_path: Path,
    force_rebuild: bool = False,
) -> faiss.Index:
    """
    Concatenate embeddings from multiple splits and build one shared index.

    Parameters
    ----------
    splits:       List of split names, e.g. ["train", "val", "test"].
    emb_dir:      Directory containing ``{split}_embeddings.npy`` files.
    output_path:  Output path for the merged FAISS index.
    force_rebuild: Rebuild even if output_path already exists.

    Returns
    -------
    faiss.Index  The merged index.
    """
    arrays: list[np.ndarray] = []
    for split in splits:
        path = emb_dir / f"{split}_embeddings.npy"
        if not path.exists():
            logger.warning("Split '%s' not found at %s — skipping.", split, path)
            continue
        arr = np.load(str(path)).astype(np.float32)
        logger.info("  Loaded %s  ->  %s", path.name, arr.shape)
        arrays.append(arr)

    if not arrays:
        raise FileNotFoundError(
            f"No embedding files found in {emb_dir} for splits {splits}."
        )

    merged = np.vstack(arrays)
    logger.info("Merged embeddings shape: %s", merged.shape)

    # Save the merged array to a temporary file, then build from it
    tmp_path = output_path.parent / "_merged_embeddings.npy"
    np.save(str(tmp_path), merged)
    index = build_index(tmp_path, output_path, force_rebuild=force_rebuild)
    tmp_path.unlink(missing_ok=True)
    return index


def _print_report(
    index:           faiss.Index,
    embeddings_path: Path,
    output_path:     Path,
) -> None:
    """Print a concise build summary to stdout."""
    index_kb = output_path.stat().st_size / 1024 if output_path.exists() else 0.0
    sep = "=" * 54

    print()
    print(sep)
    print("  GeoSense-X  -  FAISS Index Report")
    print(sep)
    print(f"  Source file      :  {embeddings_path.name}")
    print(f"  Index file       :  {output_path}")
    print()
    print(f"  Number of embeddings  :  {index.ntotal:>10,}")
    print(f"  Embedding dimension   :  {index.d:>10,}")
    print(f"  Index type            :  {index.__class__.__name__}")
    print(f"  Index size            :  {index_kb:>10.2f} KB")
    print(f"  Bytes / vector        :  {index_kb * 1024 / index.ntotal:.1f}  "
          f"(d x 4 bytes = {index.d * 4})")
    print()
    print("  Search: inner product (cosine for L2-normalised vectors)")
    print(f"  Recall: 100%  (IndexFlatIP — exact brute-force)")
    print(sep)
    print()


# ─────────────────────────────────────────────────────────────────────────────
# CLI
# ─────────────────────────────────────────────────────────────────────────────

def _build_parser() -> argparse.ArgumentParser:
    default_emb = _PROJECT_DIR / "data" / "embeddings" / "train_embeddings.npy"
    default_out = _PROJECT_DIR / "data" / "index" / "faiss.index"
    default_emb_dir = _PROJECT_DIR / "data" / "embeddings"

    p = argparse.ArgumentParser(
        prog="faiss_index",
        description="Build and save a FAISS IndexFlatIP from pre-computed embeddings.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples
--------
  # Build from train split (default)
  python backend/ml/faiss_index.py

  # Force rebuild even if index already exists
  python backend/ml/faiss_index.py --force

  # Custom source / output paths
  python backend/ml/faiss_index.py \\
      --embeddings data/embeddings/train_embeddings.npy \\
      --output     data/index/faiss.index

  # Merge all splits into one index
  python backend/ml/faiss_index.py --merge-splits
""",
    )
    p.add_argument(
        "--embeddings", type=Path, default=default_emb, metavar="NPY",
        help=f"Path to embeddings .npy file (default: {default_emb.name})",
    )
    p.add_argument(
        "--output", type=Path, default=default_out, metavar="IDX",
        help=f"Destination for FAISS index (default: {default_out})",
    )
    p.add_argument(
        "--emb-dir", type=Path, default=default_emb_dir, metavar="DIR",
        help="Directory containing *_embeddings.npy (used with --merge-splits)",
    )
    p.add_argument(
        "--merge-splits", action="store_true",
        help="Concatenate train + val + test embeddings into one index",
    )
    p.add_argument(
        "--splits", nargs="+", default=["train", "val", "test"],
        metavar="SPLIT",
        help="Splits to merge (default: train val test)",
    )
    p.add_argument(
        "--force", action="store_true",
        help="Rebuild index even if output file already exists",
    )
    p.add_argument("--debug", action="store_true")
    return p


def main() -> int:
    """Entry point. Returns 0 on success, 1 on error."""
    args = _build_parser().parse_args()
    if args.debug:
        logging.getLogger().setLevel(logging.DEBUG)

    try:
        if args.merge_splits:
            index = merge_and_build(
                splits        = args.splits,
                emb_dir       = args.emb_dir,
                output_path   = args.output,
                force_rebuild = args.force,
            )
        else:
            index = build_index(
                embeddings_path = args.embeddings,
                output_path     = args.output,
                force_rebuild   = args.force,
            )

        _print_report(index, args.embeddings, args.output)
        return 0

    except (FileNotFoundError, ValueError, RuntimeError) as exc:
        logger.error("%s", exc)
        return 1
    except Exception as exc:  # noqa: BLE001
        logger.exception("Unexpected error: %s", exc)
        return 1


if __name__ == "__main__":
    sys.exit(main())
